#include<iostream>
using namespace std;

// c*i+j= index number in 1d, i&j are value of pair of index of that element and c is total number of column
int main()
{
    int a[3][4]={{5,6,7,8},{2,3,4,8},{1,2,7,6}};
    
    //printing row wise
    for(int i=0;i<3;i++)
    {
        for(int j=0;j<4;j++)
        {
            cout<<a[i][j]<<" ";
        }
        cout<<endl;
    }
    
    // printing column wise
    cout<<"Column wise "<<endl;
  
    for(int i=0;i<4;i++)
    {
        for(int j=0;j<3;j++)
        {
            cout<<a[j][i]<<" ";
        }
        cout<<endl;
    }
    cout<<endl<<endl<<a[0][2]<<endl;


    return 0;
}


























































































































































































































































































































































































































































































































